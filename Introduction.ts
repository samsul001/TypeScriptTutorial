//Typescript
//What is typescript?

//Typescript is a strongly typed programming language that builds on JavaScript
//TypeScript is developed and maintained by Microsoft, and it has gained popularity in the web development community for 
// its ability to enhance JavaScript development with features like type annotations, interfaces, and classes.
//Typescript is a superset of javascript - It adds extra features to Javascript
//Typescript compiler converts typescript code into javascript code which can be run in any browser, nodeJS or javascript engine.
//We dont directly run typescript code and it converts into javascript code and then we run the javascript code in 
// browser, Node.js or any other javascript engine.
//Without converting typescript code into javascript code, we can run typescript code in browser or Node.js using ts-node package. 
// It is a typescript execution engine for node.js

//Javascript vs Typescript:
//difference between javascript and typescript is that typescript is a strongly typed programming language that builds on javascript
//Javascript is a dynamically typed programming language, which means that variables can change types at runtime, while
//Typescript is a statically typed programming language, which means that variables have a fixed type that is determined at compile time. 
//All Javascript code is valid typescript code, but typescript adds optional static typing to the language, 
// which can help catch errors early in the development process and improve code quality.
//Typescript makes large-scale applications easier to maintain and scale, as it provides developers with a more robust and 
// structured way to write code.
//Redeclaration of variables is not allowed in typescript, but it is allowed in javascript.

